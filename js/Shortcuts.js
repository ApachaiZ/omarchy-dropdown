// Pure shortcut helpers shared by Service.qml and the tests.
//
// The service owns the async hyprctl check; these functions only decide what a
// chord means and how the generated Lua file looks. Chords must already be
// normalized by Model.normalizeShortcut().

function luaString(value) {
  // Semicolons and brackets are escaped as three-digit decimal sequences.
  // They are ordinary characters to Lua, but `hyprctl --batch` splits its
  // argument on `;` outside `[]`, and it does not parse Lua strings. Without
  // these escapes a workspace name could break out of the batch framing.
  return '"' + String(value || "").replace(/\\/g, "\\\\").replace(/"/g, '\\"')
    .replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t")
    .replace(/;/g, "\\059").replace(/\[/g, "\\091").replace(/\]/g, "\\093") + '"'
}

// Quote one argv value for the /bin/sh command that Hyprland's exec/`o.bind`
// helper runs. Application ids come from desktop files and may contain
// spaces, quotes or semicolons.
function shellQuote(value) {
  return "'" + String(value || "").replace(/'/g, "'\\''") + "'"
}

function header() {
  return [
    "-- Generated by apach.dropdown. Do not edit: Manage (m) → D.",
    "-- Loaded by ~/.config/hypr/dropdown.lua."
  ].join("\n") + "\n"
}

// Validate a normalized chord against the other enabled apps. `apps` items are
// { id, name, enabled, shortcut }. An empty chord clears the shortcut.
function validateShortcut(apps, appId, chord) {
  var value = String(chord || "")
  if (value === "") return { ok: true, chord: "" }
  for (var i = 0; i < (apps || []).length; i++) {
    var app = apps[i]
    if (!app || String(app.id) === String(appId)) continue
    if (app.enabled !== true || !app.shortcut) continue
    if (String(app.shortcut) === value) {
      var name = app.name || app.id
      return {
        ok: false,
        message: value + " is already used by " + name + ".",
        messageKey: "shortcut.alreadyUsed",
        messageArgs: [value, name],
        chord: value
      }
    }
  }
  return { ok: true, chord: value }
}

// The parts of a conflicting Hyprland bind. Kept separate from the English
// sentence so QML can render the same decision from its own catalogs.
function bindConflictInfo(binds, mask, key, appName, currentShortcut, chord) {
  var wantedKey = String(key || "").toUpperCase()
  for (var i = 0; i < (binds || []).length; i++) {
    var bind = binds[i] || {}
    if (Number(bind.modmask || 0) !== Number(mask)) continue
    if (String(bind.key || "").toUpperCase() !== wantedKey) continue
    var description = String(bind.description || "").trim()
    if (description === "Dropdown: " + appName && currentShortcut === chord) continue
    var submap = String(bind.submap || "")
    return {
      key: submap ? "shortcut.bindConflictSubmap" : "shortcut.bindConflict",
      chord: String(chord),
      description: description,
      submap: submap
    }
  }
  return null
}

// Find a conflicting Hyprland bind. `binds` is the parsed output of
// `hyprctl binds -j`; mask and key come from Model.shortcutModmask/Key.
// Reassigning an app to the chord it already owns is not a conflict.
function bindConflict(binds, mask, key, appName, currentShortcut, chord) {
  var info = bindConflictInfo(binds, mask, key, appName, currentShortcut, chord)
  if (!info) return ""
  return info.chord + " is already bound to " +
    (info.description || "an existing Hyprland binding") +
    (info.submap ? " (submap " + info.submap + ")" : "") +
    ". Choose another chord or remove that bind."
}

// Build the generated Hyprland bind file. `entries` are { id, name, shortcut }
// already sorted and de-duplicated. `prefix` is the IPC target.
function bindsFile(entries, prefix) {
  var target = String(prefix || "omarchy-shell apach.dropdown")
  var lines = header().replace(/\s+$/, "").split("\n")
  for (var i = 0; i < (entries || []).length; i++) {
    var entry = entries[i]
    lines.push("o.bind(" + luaString(entry.shortcut) + ", " +
      luaString("Dropdown: " + entry.name) + ", " +
      luaString(target + " showApp " + shellQuote(entry.id)) +
      ", { submap_universal = true })")
  }
  return lines.join("\n") + "\n"
}

// Sort and de-duplicate entries deterministically so a changed window order
// never rewrites the file and reloads Hyprland needlessly.
function sortEntries(entries) {
  var used = {}
  var out = []
  for (var i = 0; i < (entries || []).length; i++) {
    var entry = entries[i]
    if (!entry || !entry.shortcut || used[entry.shortcut]) continue
    used[entry.shortcut] = true
    out.push({ id: String(entry.id), name: String(entry.name || entry.id), shortcut: String(entry.shortcut) })
  }
  out.sort(function(a, b) {
    if (a.shortcut !== b.shortcut) return a.shortcut < b.shortcut ? -1 : 1
    var an = a.name.toLowerCase()
    var bn = b.name.toLowerCase()
    return an < bn ? -1 : (an > bn ? 1 : 0)
  })
  return out
}

if (typeof module !== "undefined") {
  module.exports = {
    luaString: luaString,
    shellQuote: shellQuote,
    header: header,
    validateShortcut: validateShortcut,
    bindConflict: bindConflict,
    bindConflictInfo: bindConflictInfo,
    bindsFile: bindsFile,
    sortEntries: sortEntries
  }
}
