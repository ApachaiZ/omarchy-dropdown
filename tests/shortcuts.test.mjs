import test from "node:test"
import assert from "node:assert/strict"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const Shortcuts = require("../js/Shortcuts.js")

const apps = [
  { id: "a", name: "Agent", enabled: true, shortcut: "SUPER + A" },
  { id: "b", name: "Discord", enabled: true, shortcut: "SUPER + SHIFT + D" },
  { id: "c", name: "Disabled", enabled: false, shortcut: "SUPER + ALT + X" }
]

test("validateShortcut rejects a chord owned by another enabled app", () => {
  assert.equal(Shortcuts.validateShortcut(apps, "a", "SUPER + SHIFT + D").ok, false)
  assert.equal(Shortcuts.validateShortcut(apps, "b", "SUPER + SHIFT + D").ok, true)
  assert.equal(Shortcuts.validateShortcut(apps, "a", "SUPER + ALT + X").ok, true)
  assert.equal(Shortcuts.validateShortcut(apps, "a", "").ok, true)
})

test("bindConflict reports the foreign bind and ignores our own current chord", () => {
  const binds = [
    { modmask: 65, key: "D", description: "Dropdown: Agent", submap: "" },
    { modmask: 65, key: "D", description: "Toggle menu", submap: "" },
    { modmask: 72, key: "left", description: "Focus left", submap: "" }
  ]
  assert.equal(
    Shortcuts.bindConflict(binds, 65, "D", "Agent", "SUPER + SHIFT + D", "SUPER + SHIFT + D"),
    "SUPER + SHIFT + D is already bound to Toggle menu. Choose another chord or remove that bind."
  )
  assert.equal(
    Shortcuts.bindConflict(binds, 65, "D", "Discord", "", "SUPER + SHIFT + D"),
    "SUPER + SHIFT + D is already bound to Dropdown: Agent. Choose another chord or remove that bind."
  )
  assert.equal(Shortcuts.bindConflict(binds, 72, "RIGHT", "Agent", "", "SUPER + ALT + RIGHT"), "")
})

test("bindsFile escapes text and sorts deterministically", () => {
  const entries = Shortcuts.sortEntries([
    { id: "b", name: 'Quote "app"', shortcut: "SUPER + SHIFT + B" },
    { id: "a", name: "Alpha", shortcut: "SUPER + A" },
    { id: "dup", name: "Duplicate", shortcut: "SUPER + A" }
  ])
  assert.deepEqual(entries.map((e) => e.id), ["a", "b"])
  const text = Shortcuts.bindsFile(entries, "omarchy-shell apach.dropdown")
  assert.match(text, /omarchy-shell apach\.dropdown showApp 'a'/)
  assert.match(text, /Quote \\"app\\"/)
  assert.match(text, /submap_universal = true/)
  assert.equal(Shortcuts.bindsFile([], "x").trim().split("\n").length, 2)
})

test("luaString cannot break out of a hyprctl batch frame", () => {
  const escaped = Shortcuts.luaString("x;dispatch hl.dsp.exec_cmd('touch /tmp/x');y[z]")
  assert.equal(escaped.includes(";"), false)
  assert.equal(escaped.includes("["), false)
  assert.equal(escaped.includes("]"), false)
  assert.match(escaped, /\\059/)
  assert.match(escaped, /\\091/)
  assert.match(escaped, /\\093/)
})

test("shellQuote protects desktop app ids in generated binds", () => {
  assert.equal(Shortcuts.shellQuote("Google Contacts"), "'Google Contacts'")
  assert.equal(Shortcuts.shellQuote("x;touch /tmp/pwn"), "'x;touch /tmp/pwn'")
  assert.equal(Shortcuts.shellQuote("it's"), "'it'\\''s'")
  const text = Shortcuts.bindsFile([
    { id: "x;touch /tmp/pwn", name: "Evil", shortcut: "SUPER + SHIFT + E" }
  ], "omarchy-shell apach.dropdown")
  // The Lua source carries the batch-safe escape; Lua decodes it back to ';'
  // inside the shell single quotes, where it is literal.
  assert.match(text, /showApp 'x\\059touch \/tmp\/pwn'/)
})

test("header is a valid Lua comment-only file", () => {
  const header = Shortcuts.header()
  assert.ok(header.includes("Generated by apach.dropdown"))
  assert.ok(header.endsWith("\n"))
})
